// Clipboard history for the bar. Text only; skips anything a password manager
// marks as concealed or transient. History: ~/.cache/sketchybar/clipboard.json (0600).
//   clip poll      add the current clipboard if it changed (prints "new")
//   clip list [n]  "index<TAB>one-line preview" for the newest n (default 10)
//   clip copy i    put entry i back on the clipboard
//   clip clear     forget everything
import AppKit

let args = CommandLine.arguments
let fm = FileManager.default
let dir = fm.homeDirectoryForCurrentUser.appendingPathComponent(".cache/sketchybar")
try? fm.createDirectory(at: dir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
let hist = dir.appendingPathComponent("clipboard.json")
let countFile = dir.appendingPathComponent("clipboard.count")
let keep = 25

func load() -> [String] {
  guard let d = try? Data(contentsOf: hist) else { return [] }
  return (try? JSONDecoder().decode([String].self, from: d)) ?? []
}
func save(_ a: [String]) {
  let d = (try? JSONEncoder().encode(a)) ?? Data("[]".utf8)
  fm.createFile(atPath: hist.path, contents: d, attributes: [.posixPermissions: 0o600])
}

let pb = NSPasteboard.general
let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

switch args.count > 1 ? args[1] : "" {
case "poll":
  let c = String(pb.changeCount)
  if (try? String(contentsOf: countFile, encoding: .utf8)) == c { exit(0) }
  try? c.write(to: countFile, atomically: true, encoding: .utf8)
  let types = Set((pb.types ?? []).map { $0.rawValue })
  guard types.isDisjoint(with: skip), let s = pb.string(forType: .string),
        !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.count <= 100_000 else { exit(0) }
  var a = load().filter { $0 != s }
  a.insert(s, at: 0)
  save(Array(a.prefix(keep)))
  print("new")
case "list":
  let n = args.count > 2 ? Int(args[2]) ?? 10 : 10
  for (i, s) in load().prefix(n).enumerated() {
    var t = s.split(whereSeparator: { $0.isWhitespace || $0.isNewline }).joined(separator: " ")
    if t.count > 48 { t = String(t.prefix(47)) + "…" }
    print("\(i)\t\(t)")
  }
case "copy":
  let a = load()
  guard args.count > 2, let i = Int(args[2]), i >= 0, i < a.count else { exit(1) }
  pb.clearContents()
  pb.setString(a[i], forType: .string)
case "clear":
  save([])
default:
  FileHandle.standardError.write(Data("usage: clip poll | list [n] | copy i | clear\n".utf8))
  exit(2)
}
